// GITHUB LIVE SYNC SERVICE (REAL-TIME REPOSITORY INTEGRATION)
// =============================================================================
function initGitHubLiveSync() {
  const repoOwner = 'Bieuulls';
  const repoName = 'unnamed-world-project';
  const cacheKey = 'gh_sync_cache_v1';
  const cacheTTL = 120 * 1000; // 2 minutes

  const starsEl = document.getElementById('ghStarsCount');
  const forksEl = document.getElementById('ghForksCount');
  const issuesEl = document.getElementById('ghIssuesCount');
  const branchEl = document.getElementById('ghBranch');
  const commitsListEl = document.getElementById('githubCommitsList');
  const pulseTextEl = document.getElementById('githubPulseText');

  function formatRelativeTime(dateString) {
    const now = new Date();
    const past = new Date(dateString);
    const diffSec = Math.floor((now - past) / 1000);

    if (diffSec < 60) return 'just now';
    const diffMin = Math.floor(diffSec / 60);
    if (diffMin < 60) return `${diffMin}m ago`;
    const diffHours = Math.floor(diffMin / 60);
    if (diffHours < 24) return `${diffHours}h ago`;
    const diffDays = Math.floor(diffDays / 24);
    if (diffDays < 30) return `${diffDays}d ago`;
    return past.toLocaleDateString();
  }

  function renderRepoData(repoData, commitsData) {
    if (starsEl && repoData) starsEl.textContent = repoData.stargazers_count ?? 0;
    if (forksEl && repoData) forksEl.textContent = repoData.forks_count ?? 0;
    if (issuesEl && repoData) issuesEl.textContent = repoData.open_issues_count ?? 0;
    if (branchEl && repoData) branchEl.textContent = repoData.default_branch || 'main';

    if (commitsListEl && Array.isArray(commitsData) && commitsData.length > 0) {
      commitsListEl.innerHTML = '';
      commitsData.slice(0, 5).forEach(item => {
        const commit = item.commit;
        const author = item.author || { login: commit.author.name, avatar_url: 'https://github.githubassets.com/images/modules/logos_page/GitHub-Mark.png' };
        const shortSha = item.sha ? item.sha.substring(0, 7) : 'commit';
        const msg = commit.message.split('\n')[0];
        const timeAgo = formatRelativeTime(commit.author.date);

        const row = document.createElement('div');
        row.className = 'commit-item';
        row.innerHTML = `
          <div class="commit-main">
            <img src="${author.avatar_url}" alt="${author.login}" class="commit-author-avatar" loading="lazy">
            <div class="commit-info">
              <a href="${item.html_url}" target="_blank" rel="noopener" class="commit-msg" title="${commit.message.replace(/"/g, '&quot;')}">${msg}</a>
              <div class="commit-meta">
                <span>by <strong>${author.login}</strong></span>
                <span>•</span>
                <span>${timeAgo}</span>
              </div>
            </div>
          </div>
          <a href="${item.html_url}" target="_blank" rel="noopener" class="commit-badge" title="View commit on GitHub">#${shortSha}</a>
        `;
        commitsListEl.appendChild(row);
      });
    }

    if (pulseTextEl) {
      const now = new Date();
      pulseTextEl.textContent = `LIVE GITHUB SYNC ACTIVE • ${now.toLocaleTimeString()}`;
    }
  }

  async function fetchLiveGitHub() {
    try {
      const cached = localStorage.getItem(cacheKey);
      if (cached) {
        try {
          const parsed = JSON.parse(cached);
          if (Date.now() - parsed.timestamp < cacheTTL) {
            renderRepoData(parsed.repo, parsed.commits);
            return;
          }
        } catch (e) {
          // ignore cache error
        }
      }

      const [repoRes, commitsRes] = await Promise.all([
        fetch(`https://api.github.com/repos/${repoOwner}/${repoName}`),
        fetch(`https://api.github.com/repos/${repoOwner}/${repoName}/commits?per_page=5`)
      ]);

      if (!repoRes.ok) throw new Error(`GitHub API HTTP ${repoRes.status}`);

      const repoData = await repoRes.json();
      const commitsData = commitsRes.ok ? await commitsRes.json() : [];

      localStorage.setItem(cacheKey, JSON.stringify({
        timestamp: Date.now(),
        repo: repoData,
        commits: commitsData
      }));

      renderRepoData(repoData, commitsData);
    } catch (err) {
      console.warn('GitHub Live Sync fallback:', err);
      if (starsEl && starsEl.textContent === '--') starsEl.textContent = '1+';
      if (forksEl && forksEl.textContent === '--') forksEl.textContent = '0';
      if (issuesEl && issuesEl.textContent === '--') issuesEl.textContent = '0';
      if (commitsListEl && commitsListEl.querySelector('.commit-loading')) {
        commitsListEl.innerHTML = `
          <div class="commit-item">
            <div class="commit-main">
              <div class="commit-info">
                <span class="commit-msg">Repository is live and active on GitHub.</span>
                <div class="commit-meta">
                  <a href="https://github.com/${repoOwner}/${repoName}" target="_blank" rel="noopener" style="color: var(--gold-primary);">View commits, proposals and issues on GitHub &rarr;</a>
                </div>
              </div>
            </div>
          </div>
        `;
      }
    }
  }

  fetchLiveGitHub();
}

