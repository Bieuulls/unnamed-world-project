// Default primary language is English
let currentLang = 'en';

// Global function to set language - accessible via window.setLanguage('en')
window.setLanguage = function(lang) {
  if (!i18nData[lang]) return;
  currentLang = lang;
  try {
    localStorage.setItem('unnamed_world_lang', lang);
  } catch (err) {}

  document.documentElement.lang = lang;
  applyTranslations(lang);
};

function applyTranslations(lang) {
  const dict = i18nData[lang];
  if (!dict) return;

  // 1. Update current language display in the button
  const currentLangDisplay = document.getElementById('currentLangDisplay');
  if (currentLangDisplay) {
    currentLangDisplay.textContent = lang.toUpperCase();
  }

  // 2. Update active state in dropdown items
  document.querySelectorAll('.lang-item').forEach(item => {
    if (item.getAttribute('data-lang') === lang) {
      item.classList.add('active');
    } else {
      item.classList.remove('active');
    }
  });

  // 3. Update all translated DOM elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  // 4. Update input placeholder
  const nameInput = document.getElementById('worldNameInput');
  if (nameInput && dict.batizar_placeholder) {
    nameInput.placeholder = dict.batizar_placeholder;
  }
}

